select
    DISTINCT
    db.AIRPORT_CODE,
    db.AIRPORT_CITY,
    db.AIRPORT_STATE_ABR,
    db.AIRPORT_STATE_NAME
FROM
    (
    SELECT 
        DISTINCT
        ORIGIN_AIRPORT_CODE as AIRPORT_CODE,
        ORIGIN_CITY as AIRPORT_CITY,
        ORIGIN_STATE_ABR as AIRPORT_STATE_ABR,
        ORIGIN_STATE_NAME as AIRPORT_STATE_NAME
    FROM {{ ref('stg_t100__market') }}
    UNION ALL
    SELECT
        DISTINCT
        DEST_AIRPORT_CODE as AIRPORT_CODE,
        DEST_CITY as AIRPORT_CITY,
        DEST_STATE_ABR as AIRPORT_STATE_ABR,
        DEST_STATE_NAME as AIRPORT_STATE_NAME
    FROM {{ ref('stg_t100__market') }}
    ) db
ORDER BY AIRPORT_CODE